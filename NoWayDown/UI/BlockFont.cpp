void BlockFont::Draw(
	const std::string& text,
	int screenX, int screenY,
	int pixelWidth, int pixelHeight,
	Craft::Color color,
	int sortingOrder)
{
	if (pixelWidth < 1)
	{
		pixelWidth = 1;
	}

	if (pixelHeight < 1)
	{
		pixelHeight = 1;
	}

	// 이 게임은 공백 문자의 배경색으로 그림을 그리므로 색을 위쪽 4비트로 옮김.
	const Color blockColor =
		static_cast<Color>(static_cast<WORD>(color) << 4);

	// 격자 한 칸을 채울 공백 묶음. 가로는 한 번의 Submit으로 끝냄.
	const std::string block(pixelWidth, ' ');

	int cursorX = screenX;

	for (char character : text)
	{
		const Glyph* glyph = FindGlyph(character);

		if (glyph)
		{
			for (int row = 0; row < 7; ++row)
			{
				for (int column = 0; column < 5; ++column)
				{
					if (glyph->rows[row][column] != '#')
					{
						continue;
					}

					// 세로로는 pixelHeight줄만큼 반복해서 채움.
					for (int line = 0; line < pixelHeight; ++line)
					{
						Renderer::Get().SubmitCells(
							block,
							Vector2(
								cursorX + column * pixelWidth,
								screenY + row * pixelHeight + line),
							blockColor,
							sortingOrder);
					}
				}
			}
		}

		// 글자 5칸 + 사이 간격 1칸.
		cursorX += 6 * pixelWidth;
	}
}

int BlockFont::MeasureWidth(const std::string& text, int pixelWidth)
{
	if (text.empty())
	{
		return 0;
	}

	// 마지막 글자 뒤의 간격은 빼고 셈.
	return (static_cast<int>(text.size()) * 6 - 1) * pixelWidth;
}

int BlockFont::MeasureHeight(int pixelHeight)
{
	return 7 * pixelHeight;
}
