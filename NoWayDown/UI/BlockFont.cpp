	const Glyph* FindGlyph(char character)
	{
		// 소문자는 대문자로 바꿔서 찾음.
		if (character >= 'a' && character <= 'z')
		{
			character = static_cast<char>(character - 'a' + 'A');
		}

		for (const Glyph& glyph : glyphTable)
		{
			if (glyph.character == character)
			{
				return &glyph;
			}
		}

		return nullptr;
	}
